#!/usr/bin/env node
/*
 * NextMetro — Internal Linking Generator
 * --------------------------------------
 * Routes internal authority from page-one hubs (/fares/, /hours/, line pages)
 * into the page-two station/line bank by injecting crawlable, in-content
 * contextual links into the static HTML.
 *
 * This is the single source of truth for the generated link mesh. Re-running it
 * is idempotent: each injected block is bounded by INTERNAL-LINKS markers and is
 * replaced (not duplicated) on every run.
 *
 * Route order and line membership are derived from repo data:
 *   - public/lines/<color>/index.html  — the curated, ordered "All Stations"
 *     lists are the canonical route sequences. We parse them once and persist
 *     the result to public/data/lines.json (the explicit per-line order field
 *     the linking logic depends on).
 *   - public/data/stations.json        — station names + slugs.
 *
 * Usage: node scripts/build-internal-links.js
 */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const PUBLIC = path.join(ROOT, 'public');
const DATA = path.join(PUBLIC, 'data');

const START = '<!-- INTERNAL-LINKS:START (generated by scripts/build-internal-links.js — do not edit by hand) -->';
const END = '<!-- INTERNAL-LINKS:END -->';

// Canonical line metadata. Colors mirror the --nm-line-* design tokens.
const LINES = [
  { slug: 'red', name: 'Red', color: '#D41140' },
  { slug: 'orange', name: 'Orange', color: '#F09500' },
  { slug: 'blue', name: 'Blue', color: '#00A8E8' },
  { slug: 'yellow', name: 'Yellow', color: '#FFD400' },
  { slug: 'green', name: 'Green', color: '#00BD45' },
  { slug: 'silver', name: 'Silver', color: '#9BA5A5' },
];
const LINE_ORDER = LINES.map((l) => l.slug);

// Tuning. WINDOW = stations either side on a line we link to ("More <Line> Line
// stations"); MAX_NEARBY caps total station→station links per page so dense
// interchange pages stay within the ~6–15 contextual-link budget.
const WINDOW = 4;
const MAX_NEARBY = 8;

// High-impression / hub stations surfaced on /hours/ (slugs validated below).
const HOURS_STATIONS = [
  'metro-center', 'foggy-bottom', 'dupont-circle', 'farragut-north', 'farragut-west',
  'new-carrollton', 'brookland-cua', 'smithsonian', 'shaw-howard-u', 'vienna',
  'gallery-place', 'union-station', 'pentagon', 'rosslyn',
];

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------
function read(file) {
  return fs.readFileSync(file, 'utf8');
}
function write(file, content) {
  fs.writeFileSync(file, content, 'utf8');
}

/**
 * Replace (or insert) the marked block immediately before `anchor`, matching the
 * anchor line's indentation. `lines` is an array of block lines (relative indent,
 * marker lines at column 0). Idempotent: an existing block is stripped first.
 */
function injectBefore(html, anchor, lines) {
  // Strip any prior block: from its leading indent through the newline after the
  // END marker. The anchor line's own indentation (which follows) is preserved.
  const re = new RegExp(
    '[ \\t]*' + escapeRe(START) + '[\\s\\S]*?' + escapeRe(END) + '\\n',
    'g'
  );
  const cleaned = html.replace(re, '');
  const idx = cleaned.indexOf(anchor);
  if (idx === -1) return null;
  const lineStart = cleaned.lastIndexOf('\n', idx - 1) + 1;
  const indent = cleaned.slice(lineStart, idx);
  const block = lines.map((l) => (l === '' ? '' : indent + l)).join('\n') + '\n';
  return cleaned.slice(0, lineStart) + block + indent + cleaned.slice(idx);
}

function escapeRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// ---------------------------------------------------------------------------
// Step 1 — Build / refresh public/data/lines.json from the line pages
// ---------------------------------------------------------------------------
function buildLines() {
  const lines = {};
  for (const meta of LINES) {
    const file = path.join(PUBLIC, 'lines', meta.slug, 'index.html');
    const html = read(file);
    // Ordered station slugs come straight from the line-station rows, which are
    // already laid out in route sequence.
    const re = /href="\/station\/([a-z0-9-]+)\/"\s+class="line-station-row/g;
    const stations = [];
    let m;
    while ((m = re.exec(html)) !== null) stations.push(m[1]);
    if (stations.length === 0) {
      throw new Error('No stations parsed for line ' + meta.slug);
    }
    lines[meta.slug] = {
      slug: meta.slug,
      name: meta.name,
      color: meta.color,
      termini: [stations[0], stations[stations.length - 1]],
      stations,
    };
  }
  write(path.join(DATA, 'lines.json'), JSON.stringify(lines, null, 2) + '\n');
  return lines;
}

// ---------------------------------------------------------------------------
// Station → line membership + nearby-station windows
// ---------------------------------------------------------------------------
function linesForStation(slug, lines) {
  return LINE_ORDER.filter((ln) => lines[ln].stations.includes(slug));
}

function nearbyOnLine(slug, line) {
  const idx = line.stations.indexOf(slug);
  if (idx === -1) return [];
  const out = [];
  for (let d = 1; d <= WINDOW; d++) {
    if (idx - d >= 0) out.push(line.stations[idx - d]);
    if (idx + d < line.stations.length) out.push(line.stations[idx + d]);
  }
  return out;
}

// ---------------------------------------------------------------------------
// HTML fragments
// ---------------------------------------------------------------------------
function linePill(ln) {
  return (
    '    <a href="/lines/' + ln.slug + '/" class="station-line-pill station-line-pill--' + ln.slug + '">' +
    '<span class="station-line-pill-dot" aria-hidden="true"></span>' + ln.name + ' Line</a>'
  );
}

function listLineName(names) {
  if (names.length === 1) return names[0] + ' Line';
  if (names.length === 2) return names[0] + ' and ' + names[1] + ' Lines';
  return names.slice(0, -1).join(', ') + ', and ' + names[names.length - 1] + ' Lines';
}

function buildStationBlock(slug, name, lines, nameBySlug) {
  const served = linesForStation(slug, lines);
  if (served.length === 0) return null;
  const lineObjs = served.map((s) => lines[s]);
  const lineMeta = served.map((s) => LINES.find((l) => l.slug === s));

  // Line pills (station → line page).
  const pills = lineMeta.map(linePill);

  // Nearby stations grouped per line. Give each line a fair share of the link
  // budget so multi-line transfers spread across every line they serve, and
  // never show the same station twice across groups.
  const quota = Math.ceil(MAX_NEARBY / lineObjs.length);
  const seen = new Set([slug]);
  let nearbyCount = 0;
  const groups = [];
  for (let i = 0; i < lineObjs.length; i++) {
    const ln = lineObjs[i];
    const meta = lineMeta[i];
    const near = nearbyOnLine(slug, ln);
    const items = [];
    let perLine = 0;
    for (const ns of near) {
      if (nearbyCount >= MAX_NEARBY || perLine >= quota) break;
      if (seen.has(ns)) continue;
      const nm = nameBySlug[ns];
      if (!nm) continue;
      seen.add(ns);
      items.push(
        '      <li><a href="/station/' + ns + '/" class="station-links-station">' + nm + ' station</a></li>'
      );
      nearbyCount++;
      perLine++;
    }
    if (items.length === 0) continue;
    groups.push('  <div class="station-links-group">');
    groups.push(
      '    <h3 class="station-links-group-title"><span class="station-links-group-dot station-links-group-dot--' +
      meta.slug + '" aria-hidden="true"></span>More ' + meta.name + ' Line stations</h3>'
    );
    groups.push('    <ul class="station-links-list">');
    groups.push(...items);
    groups.push('    </ul>');
    groups.push('  </div>');
    if (nearbyCount >= MAX_NEARBY) break;
  }

  const intro =
    served.length > 1
      ? name + ' is a transfer station on the ' + listLineName(lineMeta.map((l) => l.name)) + '. Open a line for every stop, or jump to a nearby station.'
      : name + ' is on the ' + lineMeta[0].name + ' Line. Open the line for every stop, or jump to a nearby station.';

  return [
    START,
    '<section class="station-links animate-in" aria-labelledby="station-links-heading">',
    '  <h2 class="station-links-heading" id="station-links-heading">Lines &amp; Connections</h2>',
    '  <p class="station-links-intro">' + intro + '</p>',
    '  <div class="station-links-lines">',
    ...pills,
    '  </div>',
    ...groups,
    '</section>',
    END,
  ];
}

// ---------------------------------------------------------------------------
// /fares/ — crawlable "All Stations" reference
// ---------------------------------------------------------------------------
function buildFaresBlock(stations) {
  const sorted = stations.slice().sort((a, b) => a.name.localeCompare(b.name));
  const links = sorted.map(
    (s) => '    <a href="/station/' + s.slug + '/" class="fares-station-link">' + s.name + '</a>'
  );
  return [
    START,
    '<div class="fares-section fares-stations animate-in" aria-labelledby="fares-stations-heading">',
    '  <h2 class="fares-section-heading" id="fares-stations-heading">Fares from Every Station</h2>',
    '  <p class="fares-text">Open any station for its fare calculator, live arrivals, and service hours. All ' + stations.length + ' Metrorail stations:</p>',
    '  <div class="fares-stations-grid">',
    ...links,
    '  </div>',
    '</div>',
    END,
  ];
}

// ---------------------------------------------------------------------------
// /hours/ — first & last train links for high-impression stations
// ---------------------------------------------------------------------------
function buildHoursBlock(nameBySlug) {
  const items = HOURS_STATIONS.filter((s) => nameBySlug[s]).map(
    (s) => '    <a href="/station/' + s + '/" class="hours-station-link">' + nameBySlug[s] + ' first &amp; last train</a>'
  );
  return [
    START,
    '<section class="hours-section hours-stations" aria-labelledby="hours-stations-heading">',
    '  <h2 class="hours-section-heading" id="hours-stations-heading">First &amp; Last Train by Station</h2>',
    '  <p class="hours-text">Operating hours vary slightly by station. Check first and last train times at a specific stop:</p>',
    '  <div class="hours-stations-grid">',
    ...items,
    '  </div>',
    '</section>',
    END,
  ];
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------
function main() {
  const stations = JSON.parse(read(path.join(DATA, 'stations.json')));
  const nameBySlug = {};
  for (const s of stations) nameBySlug[s.slug] = s.name;

  const lineData = buildLines();

  let stationCount = 0;
  let stationSkipped = 0;
  for (const s of stations) {
    const file = path.join(PUBLIC, 'station', s.slug, 'index.html');
    if (!fs.existsSync(file)) {
      stationSkipped++;
      continue;
    }
    const html = read(file);
    const block = buildStationBlock(s.slug, s.name, lineData, nameBySlug);
    if (!block) {
      stationSkipped++;
      continue;
    }
    const next = injectBefore(html, '</main>', block);
    if (next === null) {
      console.warn('  ! no </main> in ' + s.slug);
      stationSkipped++;
      continue;
    }
    write(file, next);
    stationCount++;
  }
  console.log('Stations updated: ' + stationCount + (stationSkipped ? (' (skipped ' + stationSkipped + ')') : ''));

  // /fares/
  const faresFile = path.join(PUBLIC, 'fares', 'index.html');
  const faresHtml = read(faresFile);
  const faresNext = injectBefore(faresHtml, '<div class="fares-disclaimer">', buildFaresBlock(stations));
  if (faresNext === null) throw new Error('fares: anchor not found');
  write(faresFile, faresNext);
  console.log('Fares updated: All Stations reference (' + stations.length + ' links)');

  // /hours/
  const hoursFile = path.join(PUBLIC, 'hours', 'index.html');
  const hoursHtml = read(hoursFile);
  const hoursNext = injectBefore(hoursHtml, '</main>', buildHoursBlock(nameBySlug));
  if (hoursNext === null) throw new Error('hours: anchor not found');
  write(hoursFile, hoursNext);
  console.log('Hours updated: First & Last Train by Station');
}

main();
