#!/usr/bin/env node
/**
 * NextMetro — /fares/ crawlable link section + calculator route map.
 *
 * The fare calculator renders its results from the WMATA API at runtime, so the
 * links it produces are not crawlable. This generates:
 *   1. a static, in-content "Fares by line" + "All stations" section below the
 *      calculator (crawlable path from the site's highest-authority page into
 *      every line and station page)
 *   2. the code -> {slug, name, lines} map fares.js needs to turn a computed
 *      route into real links, written into fares.js as a marked block
 *
 * Idempotent: reruns replace the marked blocks in place.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const L = require('./lib/nm-links.js');

const { ROOT, stations, lines, esc, injectBlock, LINE_ORDER } = L;

// ---- 1. Static section on /fares/ ----
function lineCards() {
  return LINE_ORDER.map((line) => {
    const l = lines[line];
    return (
      `        <a href="/lines/${line}/" class="fares-line-link fares-line-link--${line}">\n` +
      `          <span class="fares-line-link-name">${esc(l.name)}</span>\n` +
      `          <span class="fares-line-link-meta">${l.order.length} stations &middot; ${esc(l.termini[0])} to ${esc(l.termini[1])}</span>\n` +
      `        </a>`
    );
  }).join('\n');
}

function stationIndex() {
  const sorted = [...stations].sort((a, b) => a.name.localeCompare(b.name));
  return sorted.map((s) => {
    const dots = s.lines
      .map((line) => `<span class="fares-station-dot fares-station-dot--${line}" aria-hidden="true"></span>`)
      .join('');
    return `        <a href="/station/${s.slug}/" class="fares-station-link">${dots}${esc(s.name)}</a>`;
  }).join('\n');
}

// Both sections fold like the rest of the reference content. Content inside a
// closed <details> stays in the DOM, so the crawlable path is unaffected.
function fold(title, body) {
  return (
    `    <details class="fares-section fares-section--fold animate-in d5">\n` +
    `      <summary class="fares-section-summary">\n` +
    `        <h2 class="fares-section-heading">${title}</h2>\n` +
    `        <i class="ri-arrow-down-s-line fares-section-chevron" aria-hidden="true"></i>\n` +
    `      </summary>\n` +
    `      <div class="fares-section-body">\n` +
    body + '\n' +
    `      </div>\n` +
    `    </details>`
  );
}

function faresSection() {
  return (
    fold('Fares by Line',
      `      <p class="fares-text">\n` +
      `        Fare is set by distance, not by line — but the line tells you how far you are going. Each line page lists its stations in route order.\n` +
      `      </p>\n` +
      `      <div class="fares-line-links">\n` +
      lineCards() + '\n' +
      `      </div>`
    ) + '\n\n' +
    fold(`All ${stations.length} Metro Stations`,
      `      <p class="fares-text">\n` +
      `        Every Metrorail station, with the lines that serve it. Station pages carry live arrivals, first and last train times, and a fare calculator for that station.\n` +
      `      </p>\n` +
      `      <div class="fares-station-index">\n` +
      stationIndex() + '\n' +
      `      </div>\n` +
      `      <p class="fares-text" style="margin-top:var(--nm-space-md)">\n` +
      `        Also useful: <a href="/stations/">the searchable station directory</a>, <a href="/transfers/">transfer stations</a>, and <a href="/hours/">operating hours and train frequency</a>.\n` +
      `      </p>`
    )
  );
}

const faresFile = path.join(ROOT, 'fares', 'index.html');
let faresHtml = fs.readFileSync(faresFile, 'utf8');
faresHtml = injectBlock(faresHtml, 'fares-index', faresSection(), {
  before: '    <!-- Disclaimer -->',
});
fs.writeFileSync(faresFile, faresHtml);

// ---- 2. Route map for fares.js ----
function routeMap() {
  const entries = stations.map((s) => {
    const l = s.lines.map((x) => `'${x}'`).join(',');
    return `  ${/^[A-Z][0-9]/.test(s.code) ? s.code : "'" + s.code + "'"}: { slug: '${s.slug}', lines: [${l}] },`;
  });
  // Multi-platform partner codes resolve to the same station page.
  const partners = stations
    .filter((s) => s.partnerCode)
    .map((s) => `  ${s.partnerCode}: { slug: '${s.slug}', lines: [${s.lines.map((x) => `'${x}'`).join(',')}] },`);
  return (
    `// Generated by tools/gen-fares-links.js from public/data/stations.json — do not edit by hand.\n` +
    `var stationRoutes = {\n` +
    entries.join('\n') + '\n' +
    (partners.length ? `  // multi-platform partner codes\n` + partners.join('\n') + '\n' : '') +
    `};\n\n` +
    `var lineDisplayNames = {\n` +
    LINE_ORDER.map((line) => `  ${line}: '${lines[line].name}',`).join('\n') + '\n' +
    `};`
  );
}

const faresJsFile = path.join(ROOT, 'js', 'fares.js');
let faresJs = fs.readFileSync(faresJsFile, 'utf8');
faresJs = injectBlock(faresJs, 'station-routes', routeMap(), {
  after: "const skipCodes = ['C01', 'F01', 'F03', 'E06', 'S04', 'S09', 'S10', 'S12', 'S13', 'S14'];",
}, 'js');
fs.writeFileSync(faresJsFile, faresJs);

console.log(`/fares/: static section with ${stations.length} station links + ${LINE_ORDER.length} line links`);
console.log(`fares.js: stationRoutes map written`);
